import crypto from 'crypto';
import { db } from '../db/database.js';

/**
 * Compute HMAC-SHA256 signature for outbound webhook payload.
 * Format mirrors GitHub/Stripe best practice: `t=<unix>,v1=<hex>`.
 * @param {string} secret
 * @param {string} rawBody
 * @param {number} [timestamp]
 * @returns {string}
 */
export function signWebhookPayload(secret, rawBody, timestamp = Math.floor(Date.now() / 1000)) {
  const signedContent = `${timestamp}.${rawBody}`;
  const digest = crypto.createHmac('sha256', String(secret)).update(signedContent).digest('hex');
  return `t=${timestamp},v1=${digest}`;
}

/**
 * Verify a signed payload generated by `signWebhookPayload`.
 * @param {string} secret
 * @param {string} rawBody
 * @param {string} headerValue
 * @param {number} [toleranceSec=300]
 * @returns {boolean}
 */
export function verifyWebhookSignature(secret, rawBody, headerValue, toleranceSec = 300) {
  if (!secret || !headerValue || typeof headerValue !== 'string') return false;
  const parts = Object.fromEntries(
    headerValue.split(',').map((kv) => {
      const idx = kv.indexOf('=');
      return idx > 0 ? [kv.slice(0, idx).trim(), kv.slice(idx + 1).trim()] : ['', ''];
    })
  );
  const ts = Number(parts.t);
  const v1 = parts.v1;
  if (!Number.isFinite(ts) || !v1) return false;
  if (Math.abs(Math.floor(Date.now() / 1000) - ts) > toleranceSec) return false;

  const expected = crypto.createHmac('sha256', String(secret)).update(`${ts}.${rawBody}`).digest('hex');
  if (expected.length !== v1.length) return false;
  return crypto.timingSafeEqual(Buffer.from(expected, 'utf8'), Buffer.from(v1, 'utf8'));
}

/**
 * Deliver a single webhook request with timeout and record the delivery outcome.
 * @param {object} webhook Row from org_webhooks
 * @param {string} event Event name (e.g. 'interview.completed')
 * @param {object} payload Event payload object
 * @param {object} [opts]
 * @param {number} [opts.timeoutMs=6000]
 */
export async function deliverWebhook(webhook, event, payload, { timeoutMs = 6000 } = {}) {
  const start = Date.now();
  const deliveryId = 'whdel_' + crypto.randomBytes(8).toString('hex');
  const envelope = {
    id: deliveryId,
    event,
    createdAt: new Date().toISOString(),
    orgId: webhook.org_id,
    data: payload,
  };
  const rawBody = JSON.stringify(envelope);
  const signature = signWebhookPayload(webhook.secret, rawBody);

  let statusCode = 0;
  let responseBody = '';
  let success = 0;

  try {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), timeoutMs);
    const resp = await fetch(webhook.url, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'User-Agent': 'RoundOneAI-Webhook/1.0',
        'X-RoundOne-Event': event,
        'X-RoundOne-Delivery': deliveryId,
        'X-RoundOne-Signature': signature,
      },
      body: rawBody,
      signal: controller.signal,
    });
    clearTimeout(timer);

    statusCode = resp.status;
    responseBody = (await resp.text()).slice(0, 1000);
    success = resp.ok ? 1 : 0;
  } catch (err) {
    statusCode = 0;
    responseBody = (err.name === 'AbortError' ? `Timeout after ${timeoutMs}ms` : err.message).slice(0, 500);
    success = 0;
  }

  const durationMs = Date.now() - start;

  try {
    db.prepare(`
      INSERT INTO webhook_deliveries (id, webhook_id, org_id, event, payload, status_code, response_body, success, duration_ms)
      VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
    `).run(deliveryId, webhook.id, webhook.org_id, event, rawBody, statusCode, responseBody, success, durationMs);

    db.prepare(`
      UPDATE org_webhooks SET last_triggered_at = CURRENT_TIMESTAMP, last_status = ? WHERE id = ?
    `).run(statusCode, webhook.id);
  } catch (dbErr) {
    console.warn('Webhook delivery log error:', dbErr.message);
  }

  return {
    deliveryId,
    webhookId: webhook.id,
    event,
    statusCode,
    success: Boolean(success),
    durationMs,
    responseBody,
  };
}

/**
 * Trigger all matching active outbound webhooks for an organization.
 * Non-blocking when awaited in fire-and-forget callers, or returns settled delivery summaries.
 * @param {string} orgId
 * @param {string} event
 * @param {object} payload
 */
export async function triggerOrgWebhooks(orgId, event, payload) {
  if (!orgId || !event) return [];
  const hooks = db.prepare('SELECT * FROM org_webhooks WHERE org_id = ? AND is_active = 1').all(orgId);
  if (!hooks.length) return [];

  const matching = hooks.filter((h) => {
    const subscribed = String(h.events || '')
      .split(',')
      .map((s) => s.trim())
      .filter(Boolean);
    return subscribed.includes('*') || subscribed.includes(event);
  });

  if (!matching.length) return [];
  return Promise.all(matching.map((hook) => deliverWebhook(hook, event, payload)));
}
